// Apply reviewed Chulapa differences to pinned, unmodified Bootswatch sources.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const vendor = path.join(root, '_sass/vendor/bootswatch');
const local = path.join(root, '_sass/chulapa/skins/bootswatch');
const manifest = require('../_sass/vendor/bootswatch/source.json');
function applyPatch(source, patch) {
  const original = source.trimEnd().split('\n');
  const result = [];
  let cursor = 0;
  for (const line of patch.trimEnd().split('\n').slice(2)) {
    const hunk = line.match(/^@@ -(\d+)(?:,\d+)? \+\d+(?:,\d+)? @@/);
    if (hunk) {
      const start = Math.max(0, Number(hunk[1]) - 1);
      assert.ok(start >= cursor, 'Patch hunks must follow source order');
      result.push(...original.slice(cursor, start));
      cursor = start;
    } else if (line.startsWith('+')) result.push(line.slice(1));
    else if (line.startsWith(' ') || line.startsWith('-')) {
      assert.equal(original[cursor++], line.slice(1), 'Patch must match its pinned source exactly');
      if (line.startsWith(' ')) result.push(line.slice(1));
    } else throw new Error('Unsupported patch line: '+line);
  }
  return [...result, ...original.slice(cursor)].join('\n')+'\n';
}
function integration(skin) {
  assert.ok(manifest.adaptations.includes(skin), 'Unknown adapted Bootswatch skin');
  const sources = Object.entries(manifest.skins[skin]).map(([file, hash])=>{
    const bytes = fs.readFileSync(path.join(vendor, skin, file));
    assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'), hash, `${skin}/${file}: original source changed`);
    return bytes.toString().trimEnd();
  });
  const patch = fs.readFileSync(path.join(local, skin+'.patch'), 'utf8');
  return '// Generated by test/generate_bootswatch.js from original sources and the adjacent patch.\n'+applyPatch(sources.join('\n')+'\n', patch);
}
if (require.main === module) {
  for (const skin of manifest.adaptations) {
    const file = path.join(local, '_'+skin+'.scss');
    const expected = integration(skin);
    if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file,'utf8'), expected, `${skin}: regenerate the integration`);
    else fs.writeFileSync(file, expected);
  }
  console.log(`${manifest.adaptations.length} Bootswatch integrations ${process.argv.includes('--check')?'verified':'generated'}.`);
}
module.exports = {integration};
